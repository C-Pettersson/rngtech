package com.rngtech.content.blockentity;

/**
 * Vacuum Collapse depth and the collapse curve. A collapse's FE does not arrive evenly: output starts low and climbs to
 * its peak at the end of the cycle, and the depth set for the collapse decides how violent that climb is. Deeper
 * collapses draw more FE from each catalyst, with diminishing returns, but run longer, peak harder, and multiply the
 * recipe's instability. Shallow collapses spend catalysts faster for a flatter, gentler curve. Rated depth reproduces
 * the recipe exactly. Depth is a fraction of rated: 0.5 to 1.5.
 */
public final class VacuumCollapseDynamics {
    public static final int MIN_DEPTH = 50;
    public static final int MAX_DEPTH = 150;
    public static final int RATED_DEPTH = 100;
    private static final double ENERGY_EXPONENT = 0.6;
    private static final double DURATION_EXPONENT = 0.5;
    private static final double INSTABILITY_EXPONENT = 2.0;
    private static final int VENT_STEPS = 400;

    private VacuumCollapseDynamics() {
    }

    public static int clampDepth(int percent) {
        return Math.max(MIN_DEPTH, Math.min(MAX_DEPTH, percent));
    }

    /** FE drawn from one catalyst relative to the recipe. */
    public static double energy(int depth) {
        return Math.pow(fraction(depth), ENERGY_EXPONENT);
    }

    /** Cycle length relative to the recipe. */
    public static double duration(int depth) {
        return Math.pow(fraction(depth), DURATION_EXPONENT);
    }

    /** The recipe's instability is multiplied by this before stability divides it. */
    public static double instability(int depth) {
        return Math.pow(fraction(depth), INSTABILITY_EXPONENT);
    }

    /** Output when the collapse starts, relative to its average FE/t. */
    public static double startRate(int depth) {
        return 1.0 - 0.6 * fraction(depth);
    }

    /** Output at the end of the collapse, its peak, relative to its average FE/t. */
    public static double peakRate(int depth) {
        return 0.6 + 1.4 * fraction(depth);
    }

    /** Output at {@code progress} (0 to 1) through the collapse, relative to its average FE/t. */
    public static double rate(int depth, double progress) {
        double start = startRate(depth);
        double x = clampProgress(progress);
        return start + (peakRate(depth) - start) * Math.pow(x, exponent(depth) - 1.0);
    }

    /** The share of the collapse's FE generated by {@code progress} (0 to 1); 0 at the start and exactly 1 at the end. */
    public static double cumulative(int depth, double progress) {
        double start = startRate(depth);
        double x = clampProgress(progress);
        return start * x + (1.0 - start) * Math.pow(x, exponent(depth));
    }

    /**
     * The share of a collapse's FE above {@code cap} FE/t when it averages {@code average} FE/t: what a connector of
     * that tier cannot take, before the internal buffer absorbs any of it.
     */
    public static double fractionAbove(int depth, double average, double cap) {
        if (average <= 0.0) {
            return 0.0;
        }
        double above = 0.0;
        for (int step = 0; step < VENT_STEPS; step++) {
            double x = (step + 0.5) / VENT_STEPS;
            above += Math.max(0.0, average * rate(depth, x) - cap);
        }
        return above / VENT_STEPS / average;
    }

    /** The curve is {@code start + (peak - start) * x^(n - 1)}; n keeps its integral at exactly 1. */
    private static double exponent(int depth) {
        double start = startRate(depth);
        return (peakRate(depth) - start) / (1.0 - start);
    }

    private static double fraction(int depth) {
        return clampDepth(depth) / (double) RATED_DEPTH;
    }

    private static double clampProgress(double progress) {
        return Math.max(0.0, Math.min(1.0, progress));
    }
}
